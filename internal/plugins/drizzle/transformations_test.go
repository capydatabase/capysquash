package drizzle

import (
	"context"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestOptimizeIdentityColumns(t *testing.T) {
	t.Parallel()

	plugin := NewDrizzlePlugin()

	input := `CREATE TABLE users (
  id integer GENERATED ALWAYS AS IDENTITY (INCREMENT BY 1 START WITH 1 CACHE 1)
);`

	got := plugin.optimizeIdentityColumns(input)
	assert.Contains(t, got, "GENERATED ALWAYS AS IDENTITY")
	assert.NotContains(t, strings.ToUpper(got), "INCREMENT BY 1")
	assert.NotContains(t, strings.ToUpper(got), "START WITH 1")
	assert.NotContains(t, strings.ToUpper(got), "CACHE 1")
}

